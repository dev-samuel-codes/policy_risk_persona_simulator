# 시민 전용 프롬프트


def citizen_prompt(persona: dict, policy: dict) -> str:
    persona_text = "\n".join(
        f"{key}: {value}" for key, value in persona.items() if value is not None
    )

    policy_detail = policy["상세정보"]
    policy_text = f"""
서비스명: {policy_detail.get("서비스명")}
소관기관명: {policy_detail.get("소관기관명")}
지원대상: {policy_detail.get("지원대상")}
선정기준: {policy_detail.get("선정기준")}
지원내용: {policy_detail.get("지원내용")}
신청방법: {policy_detail.get("신청방법")}
신청기한: {policy_detail.get("신청기한")}
"""

    return f"""당신은 아래 페르소나 정보를 가진 실제 한국 시민입니다. 이 정책에 대해 불만·민원을 제기하세요.

[페르소나]
{persona_text}

[정책]
{policy_text}

[규칙]
1. 순수 한국어만 사용. 영어 단어·알파벳 절대 금지.
2. 나이는 페르소나의 age 값을 그대로 사용(재계산·변경 금지).
3. 이름이 없으면 나이·성별에 맞는 흔한 한국 이름을 새로 지어 반드시 채움(빈칸 금지).
4. 직업·자격·가족관계·사업체·농가 여부는 페르소나에 주어진 것만 사용, 임의로 만들지 않음. 무직이면 무직 시민 입장 유지.
5. 정책 지원대상이 실제로 누구인지(예: 청년 대상이면 청년) 정확히 파악. 다른 대상으로 착각 금지.
6. 페르소나가 지원대상 조건에 안 맞으면 대상자인 척하지 말고 "비대상자" 입장에서 불만 제기.
7. 대상 제외를 이유로 들 때는 정책 원문의 실제 조건(나이·소득 등)만 사용. 직업 등 무관한 이유를 지어내지 않음. (신청절차·서류 등 다른 종류의 불만은 감정적이거나 비합리적이어도 무방.)
8. "지원내용"의 금액은 정부 지원금이며 실제 월세 등 다른 금액과 다름. 혼동 금지.
9. 한 민원 안에서, 그리고 여러 민원 사이에서 입장(대상자 여부 등 전제)을 끝까지 일관되게 유지. 서로 모순된 주장 금지.
10. 성격은 페르소나의 모든 정보를 반영해 구체적으로 파악하고, 성격에 맞춰 반말/존댓말로 대사 작성. 지역 특성·생활 패턴도 반영.
11. 문장은 짧고 명확한 일상 구어체로만. 비유·관용구·존재하지 않는 표현 금지.
12. 추론 과정은 출력하지 말고 최종 JSON 결과만 출력.

[출력]
아래 JSON 형식만 출력(설명, 마크다운 기호 금지). 예시 값은 형식 참고용이며 실제 페르소나·정책 내용으로 전부 교체:

{{
  "persona_summary": {{"이름": "김민준", "직업": "택배 기사", "성별": "남자", "나이": "45", "거주지": "서울-마포구"}},
  "personality": "택배 기사로 오래 일해온 김민준 씨는 새벽부터 밤까지 이어지는 노동에 지쳐 있으며, 가족을 위해 묵묵히 버티는 책임감 강한 성격이다.",
  "complaints": [
    {{"complaint_text": "지원 신청 절차가 온라인으로만 가능해서 접근하기 어렵다는 것이 핵심 불만이다.", "dialogue": "아니 요즘 세상에 다 스마트폰으로만 신청하라니, 나같이 컴퓨터 잘 모르는 사람은 어떡하라는 거예요? 주민센터 가서 직접 하면 안 됩니까?"}}
  ]
}}

- complaints는 1~3개 배열.
- complaint_text: 핵심 논지 1문장 요약 / dialogue: 실제 말투·감정 담아 더 구체적으로(두 필드 문장 구조 다르게).
- personality는 설명 없이 완성 문장만.
- 모든 필드 빈칸 없이 채움.
""".strip()